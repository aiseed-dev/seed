def key_label(key: str, language: str) -> str:
    """行の key の表示の語。ファイルには英語の key のまま書く。知らない key はそのまま。"""
    return STRINGS.get(language, {}).get(f"key_{key}") or STRINGS["en"].get(f"key_{key}") or key


def s(word: str, language: str, **kw) -> str:
    """画面の文。無い言語は en、en にも無ければ lang.t（見出しや判定の語）。"""
    text = STRINGS.get(language, {}).get(word) or STRINGS["en"].get(word) or lang.t(word, language)
    return text.format(**kw) if kw else text


def error_text(e: Exception, language: str, **kw) -> str:
    """PhotoError、ClientError を本人の言語の一文に。word の無い例外はそのままの文。"""
    word = getattr(e, "word", None)
    if not word:
        return str(e)
    kw.setdefault("server", "")
    text = s(word, language, **kw)
    detail = getattr(e, "detail", None)
    path = getattr(e, "path", None)
    if path is not None:
        text = f"{path.name}: {text}"
    if isinstance(detail, (list, tuple)):
        detail = ("、" if language == "ja" else ", ").join(str(x) for x in detail)
    return f"{text}（{detail}）" if detail and language == "ja" else f"{text} ({detail})" if detail else text
